#!/usr/bin/env node

const pm2 = require('pm2');
const path = require('path');
const fs = require('fs');
const os = require('os');
const { execFile, execFileSync } = require('child_process');

const BOT_PATH = path.join(__dirname, '..', 'src', 'bot.js');
const WEB_PATH = path.join(__dirname, '..', 'server.js');
const CONFIG_PATH = path.join(__dirname, '..', 'config.json');
const SERVICE_NAME = 'croncord-daemon';
const WEB_SERVICE_NAME = 'croncord-web';
const WEB_PORT = 3271;
// Pre-4.0 (AttendanceBot-era) service names — removed on install so an
// upgrade never leaves duplicate daemon/web processes behind.
const LEGACY_SERVICE_NAMES = ['attendanceBot-daemon', 'attendanceBot-web'];
const LEGACY_BOOT_SCRIPT = 'start-attendancebot.sh';
const BOOT_SCRIPT = 'start-croncord.sh';

/**
 * Detects whether we are running inside Termux (Android, no root).
 * Node built for Termux reports process.platform === 'android', and the
 * Termux prefix path lives under com.termux.
 */
function isTermux() {
    return (
        process.platform === 'android' ||
        (process.env.PREFIX || '').includes('com.termux') ||
        Boolean(process.env.TERMUX_VERSION)
    );
}

/**
 * Best-effort acquisition of a Termux wake lock so Android does not suspend
 * the process while the device screen is off. Requires the `termux-api`
 * package + Termux:API app; silently continues if unavailable.
 */
function acquireTermuxWakeLock() {
    return new Promise((resolve) => {
        execFile('termux-wake-lock', (err) => {
            if (err) {
                console.log('⚠️  termux-wake-lock not available (install with: pkg install termux-api).');
                console.log('    The daemon will still run, but Android may suspend it when idle.');
            } else {
                console.log('🔒 Termux wake lock acquired (prevents Android from sleeping the daemon).');
            }
            resolve();
        });
    });
}

/**
 * On Termux there is no systemd/init and `pm2 startup` cannot register a boot
 * service without root. Instead we drop a script into ~/.termux/boot/ which the
 * Termux:Boot addon runs on device startup to resurrect the saved PM2 process.
 */
function setupTermuxBoot() {
    try {
        const bootDir = path.join(os.homedir(), '.termux', 'boot');
        fs.mkdirSync(bootDir, { recursive: true });

        const bootScript = path.join(bootDir, BOOT_SCRIPT);
        const prefix = process.env.PREFIX || '/data/data/com.termux/files/usr';
        const script = [
            `#!${prefix}/bin/sh`,
            '# Auto-generated by Croncord install-service.js',
            'termux-wake-lock 2>/dev/null || true',
            'pm2 resurrect',
            '',
        ].join('\n');

        fs.writeFileSync(bootScript, script, { mode: 0o755 });

        // Drop the pre-4.0 boot script so device boot doesn't resurrect twice.
        try {
            const legacyBoot = path.join(bootDir, LEGACY_BOOT_SCRIPT);
            if (fs.existsSync(legacyBoot)) fs.unlinkSync(legacyBoot);
        } catch (e) { /* ignore */ }
        console.log(`\n📌 Termux:Boot script created at: ${bootScript}`);
        console.log('   Install the "Termux:Boot" app from F-Droid so schedules survive a reboot.');
    } catch (err) {
        console.log(`⚠️  Could not create Termux:Boot script: ${err.message}`);
    }
}

if (!fs.existsSync(CONFIG_PATH)) {
    console.error('❌ Error: config.json not found!');
    console.error('👉 Run "npm start" first to configure your servers.\n');
    process.exit(1);
}

async function main() {
    const termux = isTermux();

    if (termux) {
        console.log('📱 Termux (Android, no-root) environment detected.');
        await acquireTermuxWakeLock();
    }

    // Process specs: Discord daemon + Web Dashboard (:3271). Absolute script
    // paths so the installer works no matter which directory it runs from.
    const apps = [
        {
            script: BOT_PATH,
            name: SERVICE_NAME,
            autorestart: true,
            max_memory_restart: '150M',
            env: { NODE_ENV: 'production' },
        },
        {
            script: WEB_PATH,
            name: WEB_SERVICE_NAME,
            autorestart: true,
            max_memory_restart: '200M',
            env: { NODE_ENV: 'production', PORT: WEB_PORT },
        },
    ];

    pm2.connect((err) => {
        if (err) {
            console.error('❌ Failed to connect to PM2:', err.message);
            process.exit(1);
        }

        const startOne = (spec) => new Promise((resolve) => {
            pm2.start(spec, (startErr) => {
                if (startErr) {
                    console.error(`❌ PM2 registration failed for "${spec.name}":`, startErr.message);
                    resolve(false);
                } else {
                    console.log(`✅ Registered "${spec.name}" (${spec.script}).`);
                    resolve(true);
                }
            });
        });

        const dropLegacy = (name) => {
            // CLI-based delete with timeout (the programmatic API can stall
            // when a target process is mid-restart).
            const runners = [];
            const localBin = path.join(__dirname, '..', 'node_modules', 'pm2', 'bin', 'pm2');
            if (fs.existsSync(localBin)) runners.push([process.execPath, [localBin]]);
            runners.push(['npx', ['pm2']]);
            for (const [cmd, prefix] of runners) {
                try {
                    execFileSync(cmd, [...prefix, 'delete', name], { timeout: 45000, stdio: 'pipe' });
                    console.log(`🧹 Removed legacy process "${name}".`);
                    return;
                } catch (e) { /* try next runner */ }
            }
        };

        (async () => {
            // Migrate pre-4.0 installs: remove AttendanceBot-era processes first.
            for (const legacy of LEGACY_SERVICE_NAMES) {
                await dropLegacy(legacy);
            }

            let okCount = 0;
            for (const spec of apps) {
                if (await startOne(spec)) okCount++;
            }

            pm2.dump(() => {
                pm2.disconnect();

                if (okCount === apps.length) {
                    console.log(`\n🎉 Croncord services installed and running!`);
                } else {
                    console.log(`\n⚠️ Installed ${okCount}/${apps.length} service(s). Check errors above.`);
                }
                console.log(`   • ${SERVICE_NAME} — Discord background daemon`);
                console.log(`   • ${WEB_SERVICE_NAME} — Web Dashboard at http://localhost:${WEB_PORT}`);

                if (termux) {
                    // No systemd on Termux: use Termux:Boot for auto-start instead of `pm2 startup`.
                    // The boot script runs `pm2 resurrect`, which revives BOTH services.
                    setupTermuxBoot();
                } else if (process.platform === 'win32') {
                    console.log('\n💡 Reboot persistence (autostart on every boot), run ONCE as Administrator:');
                    console.log('     npm install -g pm2-windows-startup');
                    console.log('     pm2-startup install');
                    console.log('   (Plain `pm2 startup` does not support Windows — the package above bridges it.)');
                } else if (process.platform === 'darwin') {
                    console.log('\n💡 Reboot persistence (autostart on every boot), run ONCE:');
                    console.log('     pm2 startup launchd   # then run the command it prints');
                    console.log('     pm2 save              # process list already saved above');
                } else {
                    console.log('\n💡 Reboot persistence (autostart on every boot), run ONCE:');
                    console.log('     pm2 startup systemd   # then run the command it prints');
                    console.log('     pm2 save              # process list already saved above');
                }

                console.log('\n📌 Commands:');
                console.log('  - Status (both) : npm run service:status');
                console.log('  - Daemon logs   : npm run service:logs');
                console.log('  - Web logs      : npm run service:web:logs');
                console.log('  - Stop all      : npm run service:uninstall\n');
            });
        })();
    });
}

main();
